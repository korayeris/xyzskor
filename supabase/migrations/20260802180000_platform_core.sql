create or replace function public.get_match_prediction_consensus(p_match_id text)
returns table(total bigint, home_count bigint, draw_count bigint, away_count bigint, home_pct numeric, draw_pct numeric, away_pct numeric)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with allowed as (
    select id from public.matches
    where id = p_match_id and now() >= kickoff - interval '15 minutes'
  ), counts as (
    select
      count(*)::bigint as total,
      count(*) filter (where pick='1')::bigint as home_count,
      count(*) filter (where pick='X')::bigint as draw_count,
      count(*) filter (where pick='2')::bigint as away_count
    from public.predictions p join allowed a on a.id = p.match_id
  )
  select total, home_count, draw_count, away_count,
    round(100.0 * home_count / nullif(total,0), 1),
    round(100.0 * draw_count / nullif(total,0), 1),
    round(100.0 * away_count / nullif(total,0), 1)
  from counts;
$$;

