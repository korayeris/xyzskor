create or replace function public.change_team_once(new_team text)
returns public.profiles
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  changed public.profiles;
begin
  if auth.uid() is null then raise exception 'Oturum gerekli.'; end if;
  if new_team not in ('Beşiktaş','Diğer','Fenerbahçe','Galatasaray','Trabzonspor') then
    raise exception 'Geçersiz takım.';
  end if;
  update public.profiles
  set team = new_team, team_changed = true, updated_at = now()
  where id = auth.uid() and team_changed = false and team <> new_team
  returning * into changed;
  if changed.id is null then raise exception 'Takım değişikliği kullanılamıyor.'; end if;
  return changed;
end;
$$;

create or replace function public.enforce_prediction_integrity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_match public.matches;
begin
  if auth.uid() is not null and new.user_id <> auth.uid() then
    raise exception 'Başka kullanıcı adına tahmin kaydedilemez.';
  end if;
  select * into target_match from public.matches where id = new.match_id;
  if target_match.id is null then raise exception 'Maç bulunamadı.'; end if;
  if target_match.status in ('iptal','ertelendi') then raise exception 'Bu maç tahmine kapalı.'; end if;
  if now() >= target_match.kickoff - interval '15 minutes' then
    raise exception 'Tahmin süresi doldu.';
  end if;
  new.submitted_at := now();
  return new;
end;
$$;

