create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and is_admin = true
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  candidate text;
  supported_team text;
begin
  candidate := left(coalesce(nullif(trim(new.raw_user_meta_data->>'username'), ''), split_part(new.email, '@', 1), 'taraftar'), 40);
  if exists (select 1 from public.profiles where lower(username) = lower(candidate)) then
    candidate := left(candidate, 31) || '-' || substr(new.id::text, 1, 8);
  end if;
  supported_team := coalesce(nullif(trim(new.raw_user_meta_data->>'team'), ''), 'Diğer');
  if supported_team not in ('Beşiktaş','Diğer','Fenerbahçe','Galatasaray','Trabzonspor') then
    supported_team := 'Diğer';
  end if;
  insert into public.profiles (id, username, team)
  values (new.id, candidate, supported_team)
  on conflict (id) do nothing;
  return new;
end;
$$;

